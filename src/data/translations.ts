export const formatPrice = (priceUsd: number, priceRub: number, lang: Lang): string => {
  if (lang === 'ru') {
    return `${priceRub.toLocaleString('ru-RU')} ₽`;
  }
  return `$${priceUsd.toFixed(2)}`;
};

